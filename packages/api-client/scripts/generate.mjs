// Regenerates src/generated/*.ts from the OpenAPI documents the APIs build from their routes.
// Run after changing a route or schema: pnpm api:types
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const targets = [
  { name: "api", pkg: "@stroybazaar/api" },
  { name: "admin", pkg: "@stroybazaar/admin-api" },
];

const dir = mkdtempSync(join(tmpdir(), "stroybazaar-openapi-"));
try {
  for (const { name, pkg } of targets) {
    const spec = join(dir, `${name}.yaml`);
    execFileSync("pnpm", ["--filter", pkg, "openapi:export", spec], { stdio: "inherit", shell: true });
    const ast = await openapiTS(pathToFileURL(spec));
    const out = new URL(`../src/generated/${name}.ts`, import.meta.url);
    writeFileSync(out, `// Generated by \`pnpm api:types\` from ${pkg}. Do not edit.\n\n${astToString(ast)}`);
    console.log(`Generated src/generated/${name}.ts`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
